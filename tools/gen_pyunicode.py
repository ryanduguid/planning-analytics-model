"""Generate src/pyunicode.rs for the pacioliscube Rust port from this CPython's Unicode data.

Run with the base revision's locked interpreter:
    python tools/gen_pyunicode.py > src/pyunicode.rs
"""
import sys
import unicodedata

if (
    sys.implementation.name != "cpython"
    or sys.version_info[:3] != (3, 15, 0)
    or unicodedata.unidata_version != "17.0.0"
):
    raise SystemExit("Use CPython 3.15.0 with Unicode 17.0.0, matching the base release")


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def fmt_ranges(name, rs):
    body = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in rs)
    return f"pub static {name}: &[(u32, u32)] = &[\n{body}\n];\n"


def mapping(name, fn):
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        f = fn(c)
        if f != c:
            esc = "".join("\\u{%X}" % ord(x) for x in f)
            rows.append(f'    (0x{cp:04X}, "{esc}"),')
    return f"pub static {name}: &[(u32, &str)] = &[\n" + "\n".join(rows) + "\n];\n"


def not_surrogate(pred):
    return lambda cp: not 0xD800 <= cp <= 0xDFFF and pred(chr(cp))


SIGMA = "Σ"
FINAL = "ς"


# str.lower applies the Final_Sigma rule, which reads two properties CPython
# does not expose. Both are recovered from lower() itself: a character that
# ends the scan and is cased, or one the scan skips.
def scan_stops_cased(c):
    return (c + SIGMA).lower()[-1] == FINAL


def case_ignorable(c):
    return not scan_stops_cased(c) and ("A" + c + SIGMA).lower()[-1] == FINAL


out = [
    "// Generated by gen_pyunicode.py from CPython "
    f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
    "// The str predicates and case mappings the Python engine's output depended on.",
    "",
    fmt_ranges("NOT_PRINTABLE", ranges(lambda c: not chr(c).isprintable())),
    fmt_ranges("SPACE", ranges(lambda c: chr(c).isspace())),
    fmt_ranges("DECIMAL", ranges(lambda c: chr(c).isdecimal())),
    fmt_ranges("DIGIT", ranges(lambda c: chr(c).isdigit())),
    fmt_ranges("ALPHA", ranges(lambda c: chr(c).isalpha())),
    fmt_ranges("ALNUM", ranges(lambda c: chr(c).isalnum())),
    fmt_ranges("CASED", ranges(not_surrogate(scan_stops_cased))),
    fmt_ranges("CASE_IGNORABLE", ranges(not_surrogate(case_ignorable))),
    mapping("CASEFOLD", str.casefold),
    mapping("UPPER", str.upper),
    mapping("LOWER", lambda c: c.lower() if c != SIGMA else c),
]
zero = [cp for cp in range(0x110000) if chr(cp).isdecimal() and unicodedata.decimal(chr(cp)) == 0]
out.append("pub static DECIMAL_ZERO: &[u32] = &[\n" + "\n".join(f"    0x{c:04X}," for c in zero) + "\n];\n")
sys.stdout.buffer.write("\n".join(out).encode("utf-8"))
